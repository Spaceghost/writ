// Native acceptance: actual signed S3 requests, disk files, process termination
// and recovery. Pure policy scenarios live in writfs/drive/*Tests.bend.
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir, copyFile, lstat, unlink } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { Broker, privateDirectory } from './broker.mjs';
import { load } from './policy.mjs';
const [policyDir, connectionFile, output, child] = process.argv.slice(2);
assert(policyDir && connectionFile && output, 'Pass policy directory, private S3 connection JSON, and new evidence directory.');
const { default: policy } = await import(pathToFileURL(join(resolve(policyDir), 'drive.mjs')));
const { default: sync } = await import(pathToFileURL(join(resolve(policyDir), 'directory-sync.mjs')));
const directory = resolve(output), folder = directory + '-files';
const config = JSON.parse(await readFile(connectionFile));
await privateDirectory(directory);
if (child === '--crash-child') {
  const b = await new Broker(policy, sync, directory, folder).initialize();
  const event = b.event.bind(b);
  b.event = async (...args) => { await event(...args); if (args[0] === 'pending') process.exit(73); };
  await b.transfer({ connection: 1, path: 'interrupted.txt', source: 0, expected: 0, extra: 1, kind: 'save' }, Buffer.from('recover this exact pending operation'));
  throw Error('Crash point was not reached.');
}
const passed = [];
function check(name, condition = true) { assert(condition, name); passed.push(name); console.log('PASS ' + name); }
const b = await new Broker(policy, sync, directory, folder).initialize();
const prefix = config.prefix + '/acceptance-' + randomBytes(10).toString('hex');
await b.connect({ ...config, prefix: prefix + '/private', name: 'Private storage', clearance: 3 });
await b.connect({ ...config, prefix: prefix + '/public', name: 'Public destination', clearance: 0 });
await b.connect({ ...config, prefix: prefix + '/archive', name: 'Approved archive', clearance: 3 });
check('three real S3 connections enforce conditional creation, replacement and competing writes');
check('metadata-only browse fetches no file payload', b.status().fetched === 0);
const content = Buffer.from('Original notes\n');
const initial = await b.transfer({ connection: 1, path: 'Documents/notes.txt', source: 0, expected: 0, extra: 1, kind: 'save' }, content);
check('ingress persisted and exact S3 readback verified', initial.restrictions === 1 && !b.view().pending);
const before = b.sent;
await assert.rejects(b.transfer({ connection: 2, path: 'blocked.txt', source: initial.version, expected: 0, extra: 0, kind: 'copy' }));
check('denied copy sends zero destination payload', b.sent === before && (await b.client(2).list(b.client(2).key('objects/'))).items.length === 0);
const copied = await b.transfer({ connection: 3, path: 'notes-copy.txt', source: initial.version, expected: 0, extra: 0, kind: 'copy' });
check('approved cross-storage copy preserves original bytes and provenance', (await b.fetch(copied)).equals(content) && policy.provenance(b.state, copied.version).includes('100001:1:1'));
await assert.rejects(b.transfer({ connection: 2, path: 'renamed-copy.txt', source: copied.version, expected: 0, extra: 0, kind: 'copy' }));
check('copying or renaming retained output cannot erase the original restriction');
const path = await b.keep(initial.version);
check('hydration creates a real ordinary desktop file', (await readFile(path)).equals(content) && (await lstat(path)).isFile());
await writeFile(path, 'Edited in an ordinary desktop file\n'); await b.syncWorking();
let current = b.status().files.find(f => f.id === initial.id);
check('normal filesystem save syncs a new verified version', current.version > initial.version && (await b.fetch(current)).toString().startsWith('Edited'));
const secondDir = directory + '-second'; await privateDirectory(secondDir);
await copyFile(join(directory, 'connections'), join(secondDir, 'connections'));
const second = await new Broker(policy, sync, secondDir, directory + '-second-files').initialize();
check('fresh instance reconstructs full policy and history without fetching bytes', second.fetched === 0 && policy.dump(second.state) === policy.dump(b.state));
const secondPath = await second.keep(current.version);
await writeFile(path, 'First client won\n'); await b.syncWorking();
await writeFile(secondPath, 'Second client edit must survive\n'); await second.syncWorking();
check('competing edit stays local and reports conflict', (await readFile(secondPath, 'utf8')) === 'Second client edit must survive\n' && second.status().files.find(f => f.id === initial.id).status.includes('Conflict'));
current = b.status().files.find(f => f.id === initial.id);
const restricted = await b.transfer({ connection: 1, path: current.path, source: current.version, expected: current.version, extra: 2, kind: 'restrict' });
const restored = await b.transfer({ connection: 1, path: current.path, source: initial.version, expected: restricted.version, extra: 0, kind: 'restore' });
check('history restore returns old bytes while retaining newer restrictions', restored.restrictions === 3 && (await b.fetch(restored)).equals(content));
await assert.rejects(b.transfer({ connection: 2, path: 'restored-public.txt', source: restored.version, expected: 0, extra: 0, kind: 'copy' }));
check('restored history does not reopen public export');
await b.configure(3, 3, false);
await assert.rejects(b.transfer({ connection: 1, path: 'revoked-source.txt', source: copied.version, expected: 0, extra: 0, kind: 'copy' }));
check('revoked source cannot be copied through another active destination');
await b.configure(3, 3, true);
const serialized = policy.dump(b.state);
assert.throws(() => load(policy, serialized.replace('copy\t1', 'copy\t0')));
check('catalog decoder independently reconstructs inherited restrictions');
const exitCode = await new Promise((resolve, reject) => {
  const child = spawn(process.execPath, [fileURLToPath(import.meta.url), policyDir, connectionFile, directory, '--crash-child'], { stdio: ['ignore', 'pipe', 'pipe'] });
  child.stdout.resume(); child.stderr.on('data', chunk => process.stderr.write(chunk)); child.on('error', reject); child.on('exit', resolve);
});
assert.equal(exitCode, 73);
const recovered = await new Broker(policy, sync, directory, folder).initialize();
check('terminated process leaves a durable pending intent, not a synced file', !!recovered.view().pending && !recovered.status().files.some(f => f.path === 'interrupted.txt'));
await recovered.finishPending();
check('new process completes exact pending operation from private recovery', !recovered.view().pending && (await recovered.fetch(recovered.status().files.find(f => f.path === 'interrupted.txt'))).toString() === 'recover this exact pending operation');
const external = recovered.client(1), key = external.key('incoming-existing.txt');
const put = await external.put(key, Buffer.from('Existing object remains unchanged'));
const imported = await recovered.importExisting({ connection: 1, key, etag: put.headers.etag, path: 'Imported/existing.txt', extra: 1 });
check('existing S3 object is imported at its exact ETag without replacing it', (await recovered.fetch(imported)).toString() === 'Existing object remains unchanged' && (await external.get(key)).headers.etag === put.headers.etag);
const importedPath = await recovered.keep(imported.version);
await unlink(importedPath); await recovered.syncWorking();
check('local removal is reported while the exact cloud version remains recoverable', recovered.status().files.find(f => f.id === imported.id).status.includes('Local file removed') && (await recovered.fetch(imported)).toString() === 'Existing object remains unchanged');
const status = JSON.stringify(recovered.status());
check('UI status and activity contain no storage credentials', !status.includes(config.accessKey) && !status.includes(config.secretKey));
if (process.platform === 'win32') {
  check('Windows config uses account-bound DPAPI protection', !(await readFile(join(directory, 'connections'))).includes(Buffer.from(config.secretKey)));
} else check('Linux credentials are private to the local account', ((await lstat(join(directory, 'connections'))).mode & 0o077) === 0);
await writeFile(join(directory, 'acceptance.json'), JSON.stringify({ platform: process.platform, node: process.version, backend: new URL(config.endpoint).hostname, passed, prefix }, null, 2));
console.log(`ALL ${passed.length} NATIVE DRIVE CHECKS PASSED`);
