#ifndef WRIT_WINDOWS_PROBE_H
#define WRIT_WINDOWS_PROBE_H
#define WRIT_PROBE_MAGIC 0x57525031u

enum {
    WRIT_PROBE_READ = 1u << 0,
    WRIT_PROBE_RANGE = 1u << 1,
    WRIT_PROBE_EOF = 1u << 2,
    WRIT_PROBE_DIRECTORY = 1u << 3,
    WRIT_PROBE_WRITE = 1u << 4,
    WRIT_PROBE_STREAM = 1u << 5,
    WRIT_PROBE_NEW_FILE = 1u << 6,
    WRIT_PROBE_TCP4 = 1u << 7,
    WRIT_PROBE_TCP6 = 1u << 8,
    WRIT_PROBE_UDP4 = 1u << 9,
    WRIT_PROBE_UDP6 = 1u << 10,
    WRIT_PROBE_PUBLIC_FILE = 1u << 11,
    WRIT_PROBE_CHILD = 1u << 12,
    WRIT_PROBE_CONSOLE = 1u << 13,
    WRIT_PROBE_BROKER = 1u << 14,
    WRIT_PROBE_CLIPBOARD = 1u << 15,
    WRIT_PROBE_COM = 1u << 16,
    WRIT_PROBE_REVOKED_OPEN = 1u << 17,
    WRIT_PROBE_REVOKED_READ = 1u << 18
};

typedef struct {
    unsigned int magic, phase, passed, failed;
    unsigned int errors[19];
} WRIT_PROBE_REPORT;

#define WRIT_PROBE_MOUNT_MASK ((1u << 7) - 1)
#define WRIT_PROBE_NETWORK_MASK (WRIT_PROBE_TCP4 | WRIT_PROBE_TCP6 | WRIT_PROBE_UDP4 | WRIT_PROBE_UDP6)
#define WRIT_PROBE_CONFINEMENT_MASK (WRIT_PROBE_NETWORK_MASK | WRIT_PROBE_PUBLIC_FILE | WRIT_PROBE_CHILD | WRIT_PROBE_CONSOLE | WRIT_PROBE_BROKER | WRIT_PROBE_CLIPBOARD | WRIT_PROBE_COM)
#define WRIT_PROBE_REVOKE_MASK (WRIT_PROBE_REVOKED_OPEN | WRIT_PROBE_REVOKED_READ)

#endif
